// Global helper to build default status data for any missing curriculum items
function buildDefaultCourseStatusData() {
  const statusData = typeof defaultCourseStatusData !== 'undefined' ? JSON.parse(JSON.stringify(defaultCourseStatusData)) : {};
  if (typeof curriculumData !== 'undefined' && Array.isArray(curriculumData)) {
    curriculumData.forEach(course => {
      if (!statusData[course.id]) {
        const matchedList = (typeof courseTraineeMap !== 'undefined' && courseTraineeMap[course.id]) ? courseTraineeMap[course.id] : [];
        statusData[course.id] = {
          status: "미진행",
          progress: 0,
          targetCount: matchedList.length,
          completedCount: 0,
          extraCount: 0,
          eduDate: "",
          checkedTrainees: [],
          round1Trainees: [],
          round2Trainees: []
        };
      } else {
        if (typeof courseTraineeMap !== 'undefined' && courseTraineeMap[course.id]) {
          statusData[course.id].targetCount = courseTraineeMap[course.id].length;
        }
      }
    });
  }
  return statusData;
}

// Global helper to load course status data with localStorage fallback & sync
function getStoredCourseStatusData() {
  let data = null;
  try {
    const saved = localStorage.getItem('sampyo_admin_course_status_v3');
    if (saved) {
      data = JSON.parse(saved);
    }
  } catch (e) {
    console.error('Error loading sampyo_admin_course_status_v3:', e);
  }

  if (!data) {
    data = buildDefaultCourseStatusData();
  } else {
    // Ensure all courses in curriculumData exist in data
    if (typeof curriculumData !== 'undefined' && Array.isArray(curriculumData)) {
      curriculumData.forEach(course => {
        if (!data[course.id]) {
          const matchedList = (typeof courseTraineeMap !== 'undefined' && courseTraineeMap[course.id]) ? courseTraineeMap[course.id] : [];
          data[course.id] = {
            status: "미진행",
            progress: 0,
            targetCount: matchedList.length,
            completedCount: 0,
            extraCount: 0,
            eduDate: "",
            checkedTrainees: [],
            round1Trainees: [],
            round2Trainees: []
          };
        }
      });
    }
  }

  // Self-healing 1:1 alignment between completedCount and checkedTrainees
  if (typeof curriculumData !== 'undefined' && Array.isArray(curriculumData) && data) {
    let needsResave = false;
    curriculumData.forEach(course => {
      const item = data[course.id];
      if (!item) return;

      const matchedList = (typeof courseTraineeMap !== 'undefined' && courseTraineeMap[course.id]) 
        ? courseTraineeMap[course.id] 
        : [];
      const matched = matchedList.map(t => String(t.empId));

      if (item.status === '미진행' || item.completedCount === 0) {
        if ((item.checkedTrainees && item.checkedTrainees.length > 0) || item.completedCount !== 0) {
          item.status = '미진행';
          item.completedCount = 0;
          item.progress = 0;
          item.extraCount = 0;
          item.checkedTrainees = [];
          item.round1Trainees = [];
          item.round2Trainees = [];
          item.targetCount = matched.length;
          needsResave = true;
        }
      } else if (item.status === '완료') {
        item.targetCount = matched.length;
        const targetComp = item.completedCount || 0;
        const existingList = Array.from(new Set([
          ...(item.round1Trainees || []),
          ...(item.round2Trainees || []),
          ...(item.checkedTrainees || [])
        ])).filter(id => id !== 'ADMIN_JU' && matched.includes(id));

        if (existingList.length !== targetComp) {
          const candidateList = Array.from(new Set([...existingList, ...matched]));
          const finalSelected = candidateList.slice(0, targetComp);
          item.checkedTrainees = finalSelected;
          item.round1Trainees = finalSelected;
          item.round2Trainees = [];
          item.completedCount = finalSelected.length;
          needsResave = true;
        }
      }
    });

    if (needsResave) {
      try {
        localStorage.setItem('sampyo_admin_course_status_v3', JSON.stringify(data));
      } catch (e) {}
    }
  }

  return data;
}

// Global helper to save course status data
function saveStoredCourseStatusData(data) {
  try {
    localStorage.setItem('sampyo_admin_course_status_v3', JSON.stringify(data));
    if (window.completionSync && window.completionSync.configured) {
      window.completionSync.push(data).catch(error => {
        console.error('Supabase 이수현황 저장 실패:', error.message || error);
      });
    }
  } catch (e) {
    console.error('Error saving sampyo_admin_course_status_v3:', e);
  }
}
